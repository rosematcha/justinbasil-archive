#!/usr/bin/env node
// Generates public/admin/config.yml for Decap CMS. The body is a RAW markdown widget
// (modes: ['raw']) — a plain textarea that passes the preserved HTML through untouched,
// which is the whole reason we moved off Keystatic's structured MDX editor.
//
//   node scripts/gen-decap-config.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(fileURLToPath(import.meta.url), '../..');

// repo for the production (GitHub) backend; local editing uses `local_backend` + decap-server.
const REPO = 'rosematcha/justinbasil-archive';
const BRANCH = 'main';

// [name, label, widget, extraYamlProps?]
const BASE = [
  ['title', 'Title', 'string', 'required: true'],
  ['description', 'Description', 'text', 'required: false'],
  ['navTitle', 'Nav title', 'string', 'required: false'],
  ['ogImage', 'OG image path', 'string', 'required: false'],
  ['sourceUrl', 'Original URL (provenance)', 'string', 'required: false'],
  ['showHeading', 'Show heading', 'boolean', 'required: false\n        default: false'],
  ['draft', 'Draft', 'boolean', 'required: false\n        default: false'],
  ['order', 'Sort order', 'number', 'required: false\n        value_type: int'],
];
const DATE = (n, l) => [n, l, 'datetime', "required: false\n        date_format: 'YYYY-MM-DD'\n        time_format: false\n        format: 'YYYY-MM-DD'"];
const BODY = ['body', 'Body (raw)', 'markdown', "modes: ['raw']\n        buttons: []\n        editor_components: []"];

const COLLECTIONS = [
  { name: 'resources', label: 'Resources (Site Updates)', dir: 'resources',
    extra: [DATE('publishDate', 'Publish date'), ['category', 'Category', 'string', 'required: false'], ['excerpt', 'Excerpt', 'text', 'required: false']] },
  { name: 'videos', label: 'Videos', dir: 'videos',
    extra: [['youtubeId', 'YouTube video ID', 'string', 'required: false'], ['thumbnail', 'Thumbnail path', 'string', 'required: false'], DATE('publishDate', 'Publish date')] },
  { name: 'guide', label: 'Deck Building Guide', dir: 'guide' },
  { name: 'setLists', label: 'Set Lists', dir: 'set-lists' },
  { name: 'visual', label: 'Visual Set Lists', dir: 'visual' },
  { name: 'newDecks', label: 'New Decks', dir: 'new-decks' },
  { name: 'highlights', label: 'Highlights', dir: 'highlights' },
  { name: 'rotation', label: 'Rotation', dir: 'rotation' },
  { name: 'translations', label: 'Translations', dir: 'translations' },
  { name: 'proxies', label: 'Proxies', dir: 'proxies' },
  { name: 'league', label: 'League / Formats', dir: 'league' },
  { name: 'pages', label: 'Standalone Pages', dir: 'pages' },
];

function field([name, label, widget, extra]) {
  let s = `      - name: ${name}\n        label: '${label}'\n        widget: ${widget}`;
  if (extra) s += '\n        ' + extra;
  return s;
}

function collection(c) {
  const fields = [...BASE, ...(c.extra || []), BODY];
  return [
    `  - name: ${c.name}`,
    `    label: '${c.label}'`,
    `    folder: src/content/${c.dir}`,
    `    extension: md`,
    `    format: frontmatter`,
    `    create: true`,
    `    identifier_field: title`,
    `    fields:`,
    fields.map(field).join('\n'),
  ].join('\n');
}

const yml = `# Generated by scripts/gen-decap-config.mjs — edit that, then re-run.
# Local editing:  npx decap-server   (in another terminal) + open http://localhost:4321/admin/
# Production:      GitHub backend below (needs an OAuth provider) — see DEPLOY.md.
backend:
  name: github
  repo: ${REPO}
  branch: ${BRANCH}
# Lets you edit local files in dev against \`npx decap-server\` instead of GitHub.
local_backend: true

media_folder: public/images
public_folder: /images

# The bodies are preserved raw HTML+Markdown; the body field below is a RAW textarea
# (modes: ['raw']) so nothing re-parses or mangles the HTML.
collections:
${COLLECTIONS.map(collection).join('\n')}
`;

const out = path.join(ROOT, 'public/admin/config.yml');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, yml);
console.log('Wrote', path.relative(ROOT, out), `(${COLLECTIONS.length} collections)`);
